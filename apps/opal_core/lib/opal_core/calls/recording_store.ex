defmodule OpalCore.Calls.RecordingStore do
  @moduledoc """
  Repair #25 — durable storage for imported call recordings.

  Voice-note/TTS audio lives in `OpalCore.Voice.AudioStore` with a
  5 MB cap sized for clips. A call recording is a different class of
  object (minutes, not seconds), so imports get their own store with
  the same conventions: owner-scoped keys under
  `priv/local_media/call_imports/`, content-addressed file names
  (sha256), and no public URL — recordings are never share-linked;
  they are read back only by the extraction worker and the owner.
  """

  # 100 MB — a ~2h mp3 at 96 kbps is ~86 MB; beyond this the honest
  # answer is "too large for this door", never a silent truncation.
  @max_bytes 100 * 1024 * 1024

  def max_bytes, do: @max_bytes

  def root_dir do
    base =
      Application.get_env(:opal_core, :local_media_root) ||
        Path.join(:code.priv_dir(:opal_core) |> List.to_string(), "local_media")

    Path.join(base, "call_imports")
  end

  @doc "Persist a recording binary. Returns `{:ok, meta}` with the storage key."
  def put(owner_id, binary, meta \\ %{})

  def put(owner_id, binary, meta)
      when is_binary(owner_id) and is_binary(binary) do
    cond do
      byte_size(binary) == 0 ->
        {:error, :empty_audio}

      byte_size(binary) > @max_bytes ->
        {:error, :too_large}

      true ->
        sha = :crypto.hash(:sha256, binary) |> Base.encode16(case: :lower)
        ext = extension(meta[:content_type] || meta["content_type"] || "audio/mpeg")
        owner = sanitize(owner_id)
        relative = "#{owner}/#{sha}.#{ext}"
        path = Path.join(root_dir(), relative)
        File.mkdir_p!(Path.dirname(path))

        unless File.exists?(path) do
          File.write!(path, binary)
        end

        {:ok,
         %{
           "storage_key" => "call_imports/#{relative}",
           "sha256" => sha,
           "byte_size" => byte_size(binary)
         }}
    end
  end

  def put(_, _, _), do: {:error, :invalid}

  @doc "Read a stored recording back by its storage key."
  def read("call_imports/" <> relative) do
    path = Path.join(root_dir(), relative)

    # Keys are generated by put/3 from a sanitized owner id + a hex
    # digest; refuse anything that tries to walk out of the root.
    if String.contains?(relative, "..") do
      {:error, :invalid_key}
    else
      case File.read(path) do
        {:ok, binary} -> {:ok, binary}
        {:error, reason} -> {:error, reason}
      end
    end
  end

  def read(_), do: {:error, :invalid_key}

  defp extension("audio/wav"), do: "wav"
  defp extension("audio/x-wav"), do: "wav"
  defp extension("audio/wave"), do: "wav"
  defp extension("audio/mpeg"), do: "mp3"
  defp extension("audio/mp3"), do: "mp3"
  defp extension("audio/mp4"), do: "m4a"
  defp extension("audio/m4a"), do: "m4a"
  defp extension("audio/x-m4a"), do: "m4a"
  defp extension("audio/webm"), do: "webm"
  defp extension("audio/ogg"), do: "ogg"
  defp extension(_), do: "bin"

  defp sanitize(id) do
    id
    |> String.replace(~r/[^a-zA-Z0-9_-]/, "")
    |> String.slice(0, 64)
  end
end
